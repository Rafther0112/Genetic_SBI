"""
sbi_experiment.py
-----------------
Train a neural posterior estimator (NPE, flow-based) on a chosen forward
simulator, then confront it with test data from the EXACT CME. Measures:

    * parameter bias           (posterior-mean error vs true theta)
    * calibration              (SBC: are the credible intervals honest?)

Run twice -- once training on the CLE (misspecified) and once on the CME
(well-specified control) -- to isolate the effect of simulator misspecification.

Requires: sbi (>=0.24), torch, numpy.  Tested with sbi 0.26.1.
"""

import numpy as np
import torch
from sbi.inference import NPE
from sbi.utils import BoxUniform
from sbi.diagnostics import run_sbc

from telegraph import sample_cle_batched, sample_lna_batched, sample_nb_batched, summary_stats


# ----------------------------------------------------------------------
# Prior over log10 parameters (broad, biologically plausible)
#   log10 k_on  in [-2, 1.3]   (burst frequency)
#   log10 k_off in [-1, 1.3]
#   log10 k_syn in [ 0, 2.3]   (up to ~200 transcripts/lifetime)
# ----------------------------------------------------------------------
LOW = torch.tensor([-2.0, -1.0, 0.0])
HIGH = torch.tensor([1.3, 1.3, 2.3])


def make_prior():
    return BoxUniform(low=LOW, high=HIGH)


def theta_to_rates(theta_log):
    """(N,3) log10 params -> physical rates."""
    return 10.0 ** np.asarray(theta_log, dtype=np.float64)


def simulate_batch(theta_log, simulator, n_cells, rng, features="full"):
    """
    theta_log : (N, 3) tensor/array of log10 params
    simulator : 'cme' (exact Poisson-Beta) or 'cle' (misspecified Langevin)
    returns x : (N, 6) summary-stat array

    Fully vectorized: all N*n_cells trajectories are simulated at once,
    then reshaped to (N, n_cells) and reduced to summary stats per row.
    """
    theta_log = np.asarray(theta_log, dtype=np.float64)
    rates = theta_to_rates(theta_log)          # (N, 3)
    N = rates.shape[0]
    # broadcast each theta's rates across its n_cells
    kon = np.repeat(rates[:, 0], n_cells)
    koff = np.repeat(rates[:, 1], n_cells)
    ksyn = np.repeat(rates[:, 2], n_cells)

    if simulator == "cme":
        x = rng.beta(kon, koff)
        counts = rng.poisson(ksyn * x)
    elif simulator == "cle":
        counts = sample_cle_batched(kon, koff, ksyn, rng)
    elif simulator == "lna":
        counts = sample_lna_batched(kon, koff, ksyn, rng)
    elif simulator == "nb":
        counts = sample_nb_batched(kon, koff, ksyn, rng)
    else:
        raise ValueError(simulator)

    counts = counts.reshape(N, n_cells)
    return np.stack([summary_stats(counts[i], features=features) for i in range(N)])


def build_training_set(simulator, n_sims, n_cells, seed):
    rng = np.random.default_rng(seed)
    prior = make_prior()
    theta = prior.sample((n_sims,))
    x = simulate_batch(theta.numpy(), simulator, n_cells, rng)
    return theta, torch.as_tensor(x, dtype=torch.float32)


def train_npe(simulator, n_sims=8000, n_cells=500, seed=0):
    print(f"[train] building {n_sims} sims from '{simulator}' simulator ...")
    theta, x = build_training_set(simulator, n_sims, n_cells, seed)
    prior = make_prior()
    inference = NPE(prior=prior)
    inference.append_simulations(theta, x)
    density_estimator = inference.train(show_train_summary=True)
    posterior = inference.build_posterior(density_estimator)
    return posterior


def evaluate(posterior, n_test=300, n_cells=500, n_post=1000, seed=123):
    """
    Confront the trained posterior with test data generated by the EXACT CME.
    Returns per-parameter bias and SBC ranks.
    """
    rng = np.random.default_rng(seed)
    prior = make_prior()
    theta_test = prior.sample((n_test,))
    x_test = torch.as_tensor(
        simulate_batch(theta_test.numpy(), "cme", n_cells, rng),
        dtype=torch.float32,
    )

    # posterior-mean bias
    post_means = np.empty((n_test, 3))
    for i in range(n_test):
        s = posterior.sample((n_post,), x=x_test[i], show_progress_bars=False)
        post_means[i] = s.mean(0).numpy()
    bias = post_means - theta_test.numpy()  # in log10 units

    # simulation-based calibration
    ranks, _ = run_sbc(
        theta_test, x_test, posterior,
        num_posterior_samples=n_post, reduce_fns="marginals",
    )
    return {
        "theta_test": theta_test.numpy(),
        "bias": bias,
        "abs_bias": np.abs(bias),
        "sbc_ranks": np.asarray(ranks),
    }


if __name__ == "__main__":
    # Quick smoke test with small sizes (raise these for real runs)
    for sim in ["cme", "cle"]:
        post = train_npe(sim, n_sims=2000, n_cells=300, seed=1)
        out = evaluate(post, n_test=100, n_cells=300, seed=7)
        mb = out["abs_bias"].mean(0)
        print(f"\n=== trained on {sim.upper()} | eval on CME data ===")
        print(f"    mean |bias| (log10)  k_on={mb[0]:.3f}  k_off={mb[1]:.3f}  k_syn={mb[2]:.3f}")